// 처방 문자열에서 타이머 시간(초) 뽑기: "45초 × 5" → 45, "10분" → 600, 없으면 0 (스톱워치)
function exSeconds(rx) {
  const s = String(rx || "");
  const sec = s.match(/(\d+)\s*초/), min = s.match(/(\d+)\s*분/);
  if (sec) return Number(sec[1]);
  if (min) return Number(min[1]) * 60;
  return 0;
}

